// gen — генератор MarshalJSON для структур с комментарием //gen:json.
// Склеивает два предыдущих примера: дерево из ast, код из template.
// Обход полей и разбор тегов происходят один раз — при генерации.
//
// Запускается из go:generate: go run ../gen $GOFILE
// Пишет рядом файл <имя>_json.go.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"reflect"
	"strconv"
	"strings"
	"text/template"
)

type field struct {
	Name   string // имя поля в Go
	Prefix string // готовый кусок JSON перед значением: {"id": или ,"login":
	Append string // функция jsonenc для значения
	Conv   string // приведение типа перед вызовом, если нужно
	OmitIf string // omitempty: Go-условие «значение не нулевое», пусто — пишем всегда
}

type structInfo struct {
	Name   string
	Fields []field
}

const tplText = `// Code generated by gen; DO NOT EDIT.

package {{.Pkg}}

import "lecture-07/jsonenc"
{{range .Structs}}
func (v {{.Name}}) MarshalJSON() ([]byte, error) {
	buf := make([]byte, 0, 128)
{{- if not .Fields}}
	buf = append(buf, '{')
{{- end}}
{{- range .Fields}}
{{- /* omitempty: открыть if вокруг записи поля */}}
{{- if .OmitIf}}
	if {{.OmitIf}} {
{{- end}}
	buf = append(buf, {{printf "%q" .Prefix}}...)
	buf = jsonenc.{{.Append}}(buf, {{if .Conv}}{{.Conv}}(v.{{.Name}}){{else}}v.{{.Name}}{{end}})
{{- /* и закрыть его */}}
{{- if .OmitIf}}
	}
{{- end}}
{{- end}}
	return append(buf, '}'), nil
}
{{end}}`

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: gen file.go")
	}
	in := os.Args[1]

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, in, nil, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}

	var structs []structInfo
	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE || !hasMark(gd.Doc) {
			continue
		}
		ts := gd.Specs[0].(*ast.TypeSpec)
		st, ok := ts.Type.(*ast.StructType)
		if !ok {
			log.Fatalf("%s: //gen:json стоит не над структурой", ts.Name.Name)
		}
		structs = append(structs, structInfo{Name: ts.Name.Name, Fields: fields(ts.Name.Name, st)})
	}

	tpl := template.Must(template.New("marshal").Parse(tplText))
	var src bytes.Buffer
	err = tpl.Execute(&src, map[string]any{"Pkg": file.Name.Name, "Structs": structs})
	if err != nil {
		log.Fatal(err)
	}
	// gofmt для сгенерированного кода: заодно ловит синтаксические ошибки шаблона.
	out, err := format.Source(src.Bytes())
	if err != nil {
		log.Fatalf("сгенерирован некорректный код: %v\n%s", err, src.Bytes())
	}

	outName := strings.TrimSuffix(in, ".go") + "_json.go"
	if err := os.WriteFile(outName, out, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("gen: %s -> %s (%d структур)\n", in, outName, len(structs))
}

func hasMark(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, c := range doc.List {
		if strings.TrimSpace(c.Text) == "//gen:json" {
			return true
		}
	}
	return false
}

func fields(structName string, st *ast.StructType) []field {
	var res []field
	for _, f := range st.Fields.List {
		// AST — это синтаксис: мы видим имя типа как написано в коде,
		// но не знаем, что за ним стоит (type UserID int для нас просто "UserID").
		// Настоящие генераторы для этого подключают go/types.
		ident, ok := f.Type.(*ast.Ident)
		if !ok {
			log.Fatalf("%s: поддерживаются только простые типы", structName)
		}
		appendFn, conv, zero := "", "", ""
		switch ident.Name {
		case "string":
			appendFn, zero = "AppendString", ` != ""`
		case "int", "int8", "int16", "int32", "int64":
			appendFn, conv, zero = "AppendInt", "int64", " != 0"
		case "bool":
			appendFn = "AppendBool" // нулевое значение false: условие — само поле
		default:
			log.Fatalf("%s: тип %s не поддерживается", structName, ident.Name)
		}

		var tag reflect.StructTag
		if f.Tag != nil {
			raw, _ := strconv.Unquote(f.Tag.Value)
			tag = reflect.StructTag(raw) // тот же парсер тегов, что в рантайме
		}
		for _, name := range f.Names {
			if !name.IsExported() {
				continue
			}
			key, opts := name.Name, ""
			if j, ok := tag.Lookup("json"); ok {
				key, opts, _ = strings.Cut(j, ",")
				if key == "-" {
					continue
				}
				if key == "" {
					key = name.Name
				}
			}
			// Разделители вшиваются при генерации: "{" у первого поля, "," у остальных.
			// Поэтому первое поле обязано писаться всегда.
			sep := ","
			if len(res) == 0 {
				sep = "{"
			}
			cond := ""
			if opts == "omitempty" {
				if len(res) == 0 {
					log.Fatalf("%s.%s: omitempty на первом поле не поддерживается", structName, name.Name)
				}
				cond = "v." + name.Name + zero
			}
			res = append(res, field{
				Name: name.Name,
				// strconv.Quote, а не jsonenc.AppendString: для ASCII-ключей результат тот же.
				Prefix: sep + strconv.Quote(key) + ":",
				Append: appendFn,
				Conv:   conv,
				OmitIf: cond,
			})
		}
	}
	return res
}
